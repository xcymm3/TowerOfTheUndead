import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const reportFile = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'test-results/visible-english-residuals.json')
const outputFile = path.join(root, 'runtime/i18n/locales/zh-CN-residual.js')
const segmentOutputFile = path.join(root, 'runtime/i18n/locales/zh-CN-segments.js')
const tokenPattern = /(?:\d+(?:st|nd|rd|th))|(?:[-+]?\d[\d,.]*(?:e[-+]?\d+)?%?)/gi

function templateFor(text) {
  let index = 0
  return text.replace(tokenPattern, () => `<x${index++}>`)
}

async function translateRaw(text) {
  const query = new URLSearchParams({ client: 'gtx', sl: 'en', tl: 'zh-CN', dt: 't', q: text })
  for (let attempt = 0; attempt < 4; attempt++) {
    const response = await fetch(`https://translate.googleapis.com/translate_a/single?${query}`)
    if (response.ok) {
      const data = await response.json()
      return data[0].map(part => part[0]).join('')
    }
    await new Promise(resolve => setTimeout(resolve, 400 * (attempt + 1)))
  }
  throw new Error(`Translation failed: ${text}`)
}

const segmentCache = new Map()
const translateSegment = text => {
  if (!segmentCache.has(text)) segmentCache.set(text, translateRaw(text))
  return segmentCache.get(text)
}
async function translate(text) {
  let result = await translateRaw(text)
  const matches = [...result.matchAll(/[A-Za-z][A-Za-z'’ ]{1,}/g)]
    .filter(match => /[A-Za-z]{2,}/.test(match[0]))
  const replacements = await Promise.all(matches.map(match => translateSegment(match[0].trim())))
  for (let index = matches.length - 1; index >= 0; index--) {
    const match = matches[index]
    const leading = match[0].match(/^\s*/)[0]
    const trailing = match[0].match(/\s*$/)[0]
    result = result.slice(0, match.index) + leading + replacements[index] + trailing + result.slice(match.index + match[0].length)
  }
  return result
}

const report = JSON.parse(fs.readFileSync(reportFile, 'utf8'))
const existing = fs.existsSync(outputFile)
  ? JSON.parse(fs.readFileSync(outputFile, 'utf8').match(/\[[\s\S]*\]/)?.[0] ?? '[]')
  : []
const translationsBySource = new Map(existing.map(entry => [entry.source, entry]))
const sources = [...new Set(report.map(item => templateFor(item.value)))].sort()
const translations = new Array(sources.length)
let cursor = 0
async function worker() {
  while (cursor < sources.length) {
    const index = cursor++
    const source = sources[index]
    const target = await translate(source)
    translations[index] = { source, target }
    if ((index + 1) % 50 === 0 || index + 1 === sources.length) console.log(`Translated ${index + 1}/${sources.length}`)
  }
}
await Promise.all(Array.from({ length: 8 }, worker))
for (const entry of translations) translationsBySource.set(entry.source, entry)
const mergedTranslations = [...translationsBySource.values()].sort((a, b) => a.source.localeCompare(b.source))
const output = `// Generated by scripts/generate-residual-i18n.mjs from rendered UI audit output.\n` +
  `export const residualTranslations = ${JSON.stringify(mergedTranslations, null, 2)};\n`
fs.writeFileSync(outputFile, output)
const existingSegments = fs.existsSync(segmentOutputFile)
  ? JSON.parse(fs.readFileSync(segmentOutputFile, 'utf8').match(/\[[\s\S]*\]/)?.[0] ?? '[]')
  : []
const segmentsBySource = new Map(existingSegments.map(entry => [entry.source, entry]))
const segmentSources = [...new Set(report.flatMap(item => [...item.value.matchAll(/[A-Za-z][A-Za-z'’ ]{1,}/g)]
  .map(match => match[0].trim())
  .filter(source => /[a-z]{2,}/i.test(source))))]
for (const source of segmentSources) segmentsBySource.set(source, { source, target: await translateSegment(source) })
const mergedSegments = [...segmentsBySource.values()].sort((a, b) => b.source.length - a.source.length)
fs.writeFileSync(segmentOutputFile, `// Generated by scripts/generate-residual-i18n.mjs.\n` +
  `export const residualSegments = ${JSON.stringify(mergedSegments, null, 2)};\n`)
console.log(`Generated ${translations.length} translations; catalogs contain ${mergedTranslations.length} sentences and ${mergedSegments.length} segments.`)
